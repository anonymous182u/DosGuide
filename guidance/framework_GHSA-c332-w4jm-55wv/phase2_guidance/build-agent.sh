#!/bin/bash
# Build the regex-step-agent.jar from compiled test classes and ASM library.
# Must be run after `mvn package -DskipTests`.
set -e

BASEDIR="$(cd "$(dirname "$0")" && pwd)"
cd "$BASEDIR"

AGENT_BUILD=target/agent-build
rm -rf "$AGENT_BUILD"
mkdir -p "$AGENT_BUILD/com/vaadin/fuzz"
mkdir -p "$AGENT_BUILD/META-INF"

# 1. Copy agent + counter classes (including anonymous inner classes)
cp target/test-classes/com/vaadin/fuzz/RegexStepCounter.class \
   "$AGENT_BUILD/com/vaadin/fuzz/"
cp target/test-classes/com/vaadin/fuzz/RegexStepAgent.class \
   "$AGENT_BUILD/com/vaadin/fuzz/"
# Copy any inner/anonymous classes generated by javac for the agent
for f in target/test-classes/com/vaadin/fuzz/RegexStepAgent\$*.class; do
    [ -f "$f" ] && cp "$f" "$AGENT_BUILD/com/vaadin/fuzz/"
done

# 2. Extract ASM classes needed by the agent transformer
(cd "$AGENT_BUILD" && jar xf "$BASEDIR/target/deps/asm-9.8.jar" org/objectweb/asm/)

# 3. Write the manifest
cat > "$AGENT_BUILD/META-INF/MANIFEST.MF" << 'MANIFEST_EOF'
Manifest-Version: 1.0
Premain-Class: com.vaadin.fuzz.RegexStepAgent
Can-Retransform-Classes: true
Boot-Class-Path: regex-step-agent.jar
MANIFEST_EOF

# 4. Package the agent jar
jar cfm target/regex-step-agent.jar \
    "$AGENT_BUILD/META-INF/MANIFEST.MF" \
    -C "$AGENT_BUILD" com \
    -C "$AGENT_BUILD" org

echo "[build-agent] Built target/regex-step-agent.jar"
echo "[build-agent] Contents:"
jar tf target/regex-step-agent.jar | head -20
echo "..."
